class DictReader:
    # Lib/csv.py's DictReader, whose rows are dict[str, str]. It reads all the rows, and the header
    # where fieldnames is None, when it is made (CPython's fieldnames property reads the header when
    # it is first read); its first iteration makes the dicts of the rows after the header, with the
    # fieldnames it has then

    def __init__(self, f, fieldnames: list[str] | None = None, restkey: str | None = None,
                 restval: str | None = None, dialect="excel", *args, **kwds) -> None:
        self.fieldnames = fieldnames  # list of keys for the dict
        self.restkey = restkey  # key to catch long rows
        self.restval = restval  # default value for short rows
        self.reader = Reader(f, _reading(_call_dialect(dialect, *args, **kwds)))
        self.dialect = dialect
        self.line_num = 0
        p = self.reader._parse()
        self._rows: list[list[str]] = p.rows
        self._lines: list[int] = p.lines
        self._next = 0  # the first row of _rows after the header
        self._header = 0  # the line_num of the header, read here
        if fieldnames is None and len(p.rows) > 0:
            self.fieldnames = p.rows[0]
            self._header = p.lines[0]
            self._next = 1
        self.line_num = self._header
        self._started = False

    def __iter__(self) -> Iterator[dict[str, str]]:
        # __next__ until StopIteration, which leaves line_num where CPython's is then: the line of
        # the last row made a dict, or of the first of the blank rows after it
        out: list[dict[str, str]] = []
        if self._started:
            return iter(out)
        self._started = True
        rows = self._rows
        k = self._next
        line_num = self._header
        names = self.fieldnames
        while k < len(rows):
            if names is None:
                names = rows[k]
                self.fieldnames = names
                line_num = self._lines[k]
                k += 1
                continue
            row = rows[k]
            line_num = self._lines[k]
            k += 1
            # unlike the basic reader, we prefer not to return blanks,
            # because we will typically wind up with a dict full of None
            # values
            while len(row) == 0 and k < len(rows):
                row = rows[k]
                k += 1
            if len(row) == 0:
                break
            line_num = self._lines[k - 1]  # (as the fieldnames property sets it)
            d: dict[str, str] = {}
            lf = len(names)
            lr = len(row)
            for j in range(min(lf, lr)):
                d[names[j]] = row[j]
            if lf < lr:
                raise NotImplementedError("csv.DictReader puts the fields past fieldnames in a list under restkey, which the dict[str, str] Pystachy returns cannot hold")
            elif lf > lr:
                restval = self.restval
                if restval is None:
                    raise NotImplementedError("csv.DictReader gives restval None for the fields a short row lacks, which the dict[str, str] Pystachy returns cannot hold: pass a str restval")
                for key in names[lr:]:
                    d[key] = restval
            out.append(d)
        self.line_num = line_num
        return iter(out)


class DictWriter:
    # Lib/csv.py's DictWriter: a row is a dict, whose values go to the writer in fieldnames' order

    def __init__(self, f, fieldnames, restval: str | None = "", extrasaction: str = "raise", dialect="excel",
                 *args, **kwds) -> None:
        self.fieldnames = fieldnames  # list of keys for the dict
        self.restval = restval  # for writing short dicts
        extrasaction = extrasaction.lower()
        if extrasaction not in ("raise", "ignore"):
            raise ValueError("extrasaction (%s) must be 'raise' or 'ignore'"
                             % extrasaction)
        self.extrasaction = extrasaction
        self.writer = Writer(f, _call_dialect(dialect, *args, **kwds))

    def writeheader(self):
        return self.writer.writerow(self.fieldnames)

    def writerow(self, rowdict):
        if self.extrasaction == "raise":
            wrong_fields = [k for k in rowdict if k not in self.fieldnames]
            if wrong_fields:
                raise ValueError("dict contains fields not in fieldnames: "
                                 + ", ".join([repr(x) for x in wrong_fields]))
        w = self.writer
        w._parts.clear()
        w._nfields = 0
        null = False
        for key in self.fieldnames:
            if key in rowdict:
                null = w._append(rowdict[key])
            else:
                null = w._append(self.restval)
        return w._end(null)

    def writerows(self, rowdicts) -> None:
        for rowdict in rowdicts:
            self.writerow(rowdict)
