r"""
CSV parsing and writing.

This module provides classes that assist in the reading and writing
of Comma Separated Value (CSV) files, and implements the interface
described by PEP 305.  Although many CSV files are simple to parse,
the format is not formally defined by a stable specification and
is subtle enough that parsing lines of a CSV file with something
like line.split(",") is bound to fail.  The module supports three
basic APIs: reading, writing, and registration of dialects.


DIALECT REGISTRATION:

Readers and writers support a dialect argument, which is a convenient
handle on a group of settings.  When the dialect argument is a string,
it identifies one of the dialects previously registered with the module.
If it is a class or instance, the attributes of the argument are used as
the settings for the reader or writer:

    class excel:
        delimiter = ','
        quotechar = '"'
        escapechar = None
        doublequote = True
        skipinitialspace = False
        lineterminator = '\r\n'
        quoting = QUOTE_MINIMAL

SETTINGS:

    * quotechar - specifies a one-character string to use as the
        quoting character.  It defaults to '"'.
    * delimiter - specifies a one-character string to use as the
        field separator.  It defaults to ','.
    * skipinitialspace - specifies how to interpret spaces which
        immediately follow a delimiter.  It defaults to False, which
        means that spaces immediately following a delimiter is part
        of the following field.
    * lineterminator - specifies the character sequence which should
        terminate rows.
    * quoting - controls when quotes should be generated by the writer.
        It can take on any of the following module constants:

        csv.QUOTE_MINIMAL means only when required, for example, when a
            field contains either the quotechar or the delimiter
        csv.QUOTE_ALL means that quotes are always placed around fields.
        csv.QUOTE_NONNUMERIC means that quotes are always placed around
            fields which do not parse as integers or floating-point
            numbers.
        csv.QUOTE_STRINGS means that quotes are always placed around
            fields which are strings.  Note that the Python value None
            is not a string.
        csv.QUOTE_NOTNULL means that quotes are only placed around fields
            that are not the Python value None.
        csv.QUOTE_NONE means that quotes are never placed around fields.
    * escapechar - specifies a one-character string used to escape
        the delimiter when quoting is set to QUOTE_NONE.
    * doublequote - controls the handling of quotes inside fields.  When
        True, two consecutive quotes are interpreted as one during read,
        and when writing, each quote character embedded in the data is
        written as two quotes
"""

# Pystachy's csv: CPython 3.13's csv module, Lib/csv.py over the C module _csv (Modules/_csv.c),
# written in the subset as one module. A reader runs _csv.c's state machine (parse_process_char)
# over the characters of each line, a writer quotes and escapes each field as its join_append_data
# does, and a dialect is checked as dialect_new checks it, so that what csv accepts, writes and
# rejects is CPython's, with CPython's errors and their messages.
#
# The subset has no inheritance, no classes as values and no iterator classes, so:
# - excel, excel_tab and unix_dialect are Dialect objects (CPython's are subclasses of csv.Dialect),
#   and Dialect is the type CPython calls _csv.Dialect: what get_dialect() returns, and a reader's
#   or writer's dialect;
# - a reader parses all of its input when its iteration starts, and its __iter__ steps through the
#   list of rows; a DictReader reads its rows, and the header, when it is made;
# - a row is a list[str] (a list holds one type), and a DictReader's row a dict[str, str]: where
#   CPython's would hold another type (a float of QUOTE_NONNUMERIC, a None, a list under restkey),
#   NotImplementedError says so.
#
# A str holds UTF-8 in Pystachy: the state machine reads a line byte by byte, which is reading it
# character by character where the dialect's characters are ASCII (the bytes of a character past
# ASCII are no delimiter, quote, escape, space or line break), and character by character where
# one of them is not; a field's length, for field_size_limit(), counts characters.
from typing import Iterator

__all__ = ["QUOTE_MINIMAL", "QUOTE_ALL", "QUOTE_NONNUMERIC", "QUOTE_NONE",
           "QUOTE_STRINGS", "QUOTE_NOTNULL",
           "Error", "Dialect", "excel", "excel_tab",
           "field_size_limit", "reader", "writer",
           "register_dialect", "get_dialect", "list_dialects",
           "unregister_dialect", "DictReader", "DictWriter",
           "unix_dialect"]

__version__ = "1.0"

QUOTE_MINIMAL = 0
QUOTE_ALL = 1
QUOTE_NONNUMERIC = 2
QUOTE_NONE = 3
QUOTE_STRINGS = 4
QUOTE_NOTNULL = 5

_UTF8 = len("é") == 2  # (a str holds UTF-8, as in Pystachy; else code points, as in CPython)

# the states of the reader (_csv.c's ParserState), and EOL, the end of a line
_START_RECORD = 0
_START_FIELD = 1
_ESCAPED_CHAR = 2
_IN_FIELD = 3
_IN_QUOTED_FIELD = 4
_ESCAPE_IN_QUOTED_FIELD = 5
_QUOTE_IN_QUOTED_FIELD = 6
_EAT_CRNL = 7
_AFTER_ESCAPED_CRNL = 8
_EOL = -2

_field_limit = 128 * 1024  # max parsed field size


class Error(Exception):
    pass


class _NotSet:
    # a setting or argument not given (NULL in _csv.c): an object of its own type, which a template
    # tells apart from None at compile time (each is a new object, so known not to be None)
    pass


def _typename(x) -> str:
    # type(x).__name__ (Pystachy has it for exceptions): the builtin types an argument may have
    if x is None:
        return "NoneType"
    if isinstance(x, bool):
        return "bool"
    if isinstance(x, int):
        return "int"
    if isinstance(x, float):
        return "float"
    if isinstance(x, str):
        return "str"
    if isinstance(x, list):
        return "list"
    if isinstance(x, tuple):
        return "tuple"
    if isinstance(x, dict):
        return "dict"
    if isinstance(x, set):
        return "set"
    if isinstance(x, frozenset):
        return "frozenset"
    return type(x).__name__


def _width(s: str, i: int, b: int) -> int:
    # the length of the UTF-8 sequence s[i:], whose first byte is b, as Pystachy's runtime reads a
    # character (ord(), repr()): 1 where the bytes are not one
    k = 1 if b > 0xF4 else 4 if b >= 0xF0 else 3 if b >= 0xE0 else 2 if b >= 0xC2 else 1
    if k == 1 or i + k > len(s):
        return 1
    v = b & (0x7F >> k)
    for j in range(1, k):
        x = ord(s[i + j])
        if x & 0xC0 != 0x80:
            return 1
        v = (v << 6) | (x & 0x3F)
    if v < (0x80 if k == 2 else 0x800 if k == 3 else 0x10000) or v > 0x10FFFF:
        return 1
    return k


def _chars(s: str) -> list[str]:
    # the characters of s
    if not _UTF8:
        return [c for c in s]
    out: list[str] = []
    i = 0
    while i < len(s):
        b = ord(s[i])
        k = _width(s, i, b) if b >= 0x80 else 1
        out.append(s[i : i + k])
        i += k
    return out


class Dialect:
    """CSV dialect

    The Dialect type records CSV parsing and generation options.
    """

    # CPython's _csv.Dialect, which dialect_new makes and checks: here _make_dialect()

    def __init__(self, delimiter: str, quotechar: str | None, escapechar: str | None,
                 doublequote: bool, skipinitialspace: bool, lineterminator: str, quoting: int,
                 strict: bool) -> None:
        self.delimiter = delimiter
        self.quotechar = quotechar
        self.escapechar = escapechar
        self.doublequote = doublequote
        self.skipinitialspace = skipinitialspace
        self.lineterminator = lineterminator
        self.quoting = quoting
        self.strict = strict


# ---- making and checking a dialect (dialect_new and its _set_* helpers)

def _set_char(name: str, src) -> str:
    if not isinstance(src, str):
        raise TypeError('"%s" must be string, not %.200s' % (name, _typename(src)))
    if len(src) != 1 and len(_chars(src)) != 1:
        raise TypeError('"%s" must be a 1-character string' % name)
    return src


def _set_char_or_none(name: str, src) -> str | None:
    if src is None:
        return None
    if not isinstance(src, str):
        raise TypeError('"%s" must be string or None, not %.200s' % (name, _typename(src)))
    if len(src) != 1 and len(_chars(src)) != 1:
        raise TypeError('"%s" must be a 1-character string' % name)
    return src


def _set_int(name: str, src) -> int:
    if isinstance(src, bool) or not isinstance(src, int):
        raise TypeError('"%s" must be an integer' % name)
    if src < -2147483648 or src > 2147483647:
        raise OverflowError("Python int too large to convert to C int")
    return src


def _set_str(name: str, src) -> str | None:
    if src is None:
        return None
    if not isinstance(src, str):
        raise TypeError('"%s" must be a string' % name)
    return src


def _check_char(name: str, c: str | None, lineterminator: str, allowspace: bool) -> None:
    # dialect_check_char
    if c is None:
        return
    if c == "\r" or c == "\n" or (c == " " and not allowspace):
        raise ValueError("bad %s value" % name)
    if c in lineterminator:
        raise ValueError("bad %s or lineterminator value" % name)


def _make_dialect(delimiter, doublequote, escapechar, lineterminator, quotechar, quoting,
                  skipinitialspace, strict) -> Dialect:
    # dialect_new, from the value of each setting: given (by the dialect or a keyword argument) or
    # a _NotSet, for its default; the checks in its order, with its errors
    d = "," if isinstance(delimiter, _NotSet) else _set_char("delimiter", delimiter)
    dq = True if isinstance(doublequote, _NotSet) else bool(doublequote)
    esc = None if isinstance(escapechar, _NotSet) else _set_char_or_none("escapechar", escapechar)
    term = "\r\n" if isinstance(lineterminator, _NotSet) else _set_str("lineterminator",
                                                                       lineterminator)
    q = '"' if isinstance(quotechar, _NotSet) else _set_char_or_none("quotechar", quotechar)
    qs = QUOTE_MINIMAL if isinstance(quoting, _NotSet) else _set_int("quoting", quoting)
    skip = False if isinstance(skipinitialspace, _NotSet) else bool(skipinitialspace)
    st = False if isinstance(strict, _NotSet) else bool(strict)
    if qs < QUOTE_MINIMAL or qs > QUOTE_NOTNULL:
        raise TypeError('bad "quoting" value')
    if quotechar is None and isinstance(quoting, _NotSet):
        qs = QUOTE_NONE
    if qs != QUOTE_NONE and q is None:
        raise TypeError("quotechar must be set if quoting enabled")
    if term is None:
        raise TypeError("lineterminator must be set")
    _check_char("delimiter", d, term, True)
    _check_char("escapechar", esc, term, not skip)
    _check_char("quotechar", q, term, not skip)
    if d == esc:
        raise ValueError("bad delimiter or escapechar value")
    if d == q:
        raise ValueError("bad delimiter or quotechar value")
    if esc is not None and esc == q:
        raise ValueError("bad escapechar or quotechar value")
    return Dialect(d, q, esc, dq, skip, term, qs, st)


_KEYWORDS = ["delimiter", "doublequote", "escapechar", "lineterminator", "quotechar", "quoting",
             "skipinitialspace", "strict"]


def _new_dialect(base: Dialect, **kwargs) -> Dialect:
    # dialect_new(base, **kwargs): base itself where no keyword changes it, else a new dialect of
    # base's settings and the keywords'. base None is no dialect: the defaults
    if base is None:
        return _make_dialect(
            kwargs["delimiter"] if "delimiter" in kwargs else _NotSet(),
            kwargs["doublequote"] if "doublequote" in kwargs else _NotSet(),
            kwargs["escapechar"] if "escapechar" in kwargs else _NotSet(),
            kwargs["lineterminator"] if "lineterminator" in kwargs else _NotSet(),
            kwargs["quotechar"] if "quotechar" in kwargs else _NotSet(),
            kwargs["quoting"] if "quoting" in kwargs else _NotSet(),
            kwargs["skipinitialspace"] if "skipinitialspace" in kwargs else _NotSet(),
            kwargs["strict"] if "strict" in kwargs else _NotSet())
    if len(kwargs) == 0:
        if base is excel or base is excel_tab or base is unix_dialect:
            # (they stand for CPython's classes, of which dialect_new makes a new dialect)
            return Dialect(base.delimiter, base.quotechar, base.escapechar, base.doublequote,
                           base.skipinitialspace, base.lineterminator, base.quoting, base.strict)
        return base
    return _make_dialect(
        kwargs["delimiter"] if "delimiter" in kwargs else base.delimiter,
        kwargs["doublequote"] if "doublequote" in kwargs else base.doublequote,
        kwargs["escapechar"] if "escapechar" in kwargs else base.escapechar,
        kwargs["lineterminator"] if "lineterminator" in kwargs else base.lineterminator,
        kwargs["quotechar"] if "quotechar" in kwargs else base.quotechar,
        kwargs["quoting"] if "quoting" in kwargs else base.quoting,
        kwargs["skipinitialspace"] if "skipinitialspace" in kwargs else base.skipinitialspace,
        kwargs["strict"] if "strict" in kwargs else base.strict)


def _call_dialect(dialect, **kwargs) -> Dialect:
    # _call_dialect: the dialect of a reader or writer, from a registered name, a Dialect or None,
    # once dialect_new's arguments are parsed
    for k in kwargs:
        if k not in _KEYWORDS:
            raise TypeError("this function got an unexpected keyword argument '%s'" % k)
    if isinstance(dialect, str):
        d = _dialects.get(dialect)
        if d is None:
            raise Error("unknown dialect")
        return _new_dialect(d, **kwargs)
    return _new_dialect(dialect, **kwargs)


# ---- the dialect registry

_dialects: dict[str, Dialect] = {}


def register_dialect(name, /, dialect=None, **fmtparams) -> None:
    """Create a mapping from a string name to a CVS dialect.

    The optional "dialect" argument specifies the base dialect instance
    or the name of the registered dialect.  The function also accepts
    optional keyword arguments which override settings provided by the
    dialect.
    """
    if isinstance(name, str):
        _dialects[name] = _call_dialect(dialect, **fmtparams)
    else:
        raise TypeError("dialect name must be a string")


def unregister_dialect(name: str) -> None:
    """Delete the name/dialect mapping associated with a string name."""
    if name not in _dialects:
        raise Error("unknown dialect")
    del _dialects[name]


def get_dialect(name: str) -> Dialect:
    """Return the dialect instance associated with name."""
    d = _dialects.get(name)
    if d is None:
        raise Error("unknown dialect")
    return d


def list_dialects() -> list[str]:
    """Return a list of all known dialect names."""
    return list(_dialects)


def field_size_limit(new_limit=_NotSet()) -> int:
    """Sets an upper limit on parsed fields.

    Returns old limit. If limit is not given, no new limit is set and
    the old limit is returned
    """
    global _field_limit
    old = _field_limit
    if not isinstance(new_limit, _NotSet):
        if isinstance(new_limit, bool) or not isinstance(new_limit, int):
            raise TypeError("limit must be an integer")
        else:
            _field_limit = new_limit
    return old


# Describe the usual properties of Excel-generated CSV files.
excel = Dialect(",", '"', None, True, False, "\r\n", QUOTE_MINIMAL, False)
register_dialect("excel", excel)

# Describe the usual properties of Excel-generated TAB-delimited files.
excel_tab = Dialect("\t", '"', None, True, False, "\r\n", QUOTE_MINIMAL, False)
register_dialect("excel-tab", excel_tab)

# Describe the usual properties of Unix-generated CSV files.
unix_dialect = Dialect(",", '"', None, True, False, "\n", QUOTE_ALL, False)
register_dialect("unix", unix_dialect)


# ---- reading

class _Parser:
    # what _csv.c's ReaderObj keeps from one line to the next: the parse state, the fields of the
    # record so far and the text of the field so far (pieces, flen bytes long); and the records,
    # with the line_num of each one's last line. The dialect's characters are integers: a byte, or
    # a code point where wide; -1 for none (and the quotechar of QUOTE_NONE, which the reader does
    # not see). null: a field of the record so far is one QUOTE_NOTNULL makes None of

    def __init__(self, dialect: Dialect) -> None:
        self.dialect = dialect
        self.delim: int = ord(dialect.delimiter)
        self.quote: int = -1
        self.quotes = ""  # (the quotechar as a str, where quote is one)
        q = dialect.quotechar
        if q is not None and dialect.quoting != QUOTE_NONE:
            self.quote = ord(q)
            self.quotes = q
        self.esc: int = -1
        self.escs = ""
        e = dialect.escapechar
        if e is not None:
            self.esc = ord(e)
            self.escs = e
        self.wide: bool = _UTF8 and (self.delim >= 0x80 or self.quote >= 0x80 or self.esc >= 0x80)
        self.notnull: bool = dialect.quoting == QUOTE_NOTNULL
        self.state: int = _START_RECORD
        self.fields: list[str] = []
        self.pieces: list[str] = []
        self.flen: int = 0
        self.unquoted: bool = False
        self.null = False
        self.rows: list[list[str]] = []
        self.lines: list[int] = []

    def feed(self, line: str, line_num: int) -> None:
        # parse_process_char of each character of line, then of EOL (Reader_iternext's loop); a
        # record that the line ends is added to rows. The characters that parse_add_char adds to
        # the field are taken as slices of the line: start is where those since the last piece
        # begin (-1: none), and any other character ends them
        d = self.dialect
        state = self.state
        fields = self.fields
        pieces = self.pieces
        flen = self.flen
        # the continuation bytes of UTF-8 characters among the field's flen bytes, counted once flen
        # is above the limit: the field's length in characters is then flen - fcont
        fcont = 0
        counted = False
        unquoted = self.unquoted
        delim = self.delim
        quote = self.quote
        esc = self.esc
        delims = d.delimiter
        quotes = self.quotes
        escs = self.escs
        skip = d.skipinitialspace
        wide = self.wide
        limit = _field_limit
        n = len(line)
        nl = -1  # the first \r or \n of the line from where it was looked for on
        start = -1
        i = 0
        while i <= n:
            w = 1
            if i == n:
                c = _EOL
            else:
                c = ord(line[i])
                if wide and c >= 0x80:
                    w = _width(line, i, c)
                    if w > 1:
                        c = ord(line[i : i + w])
            act = 0  # 1: parse_add_char(c), 2: parse_save_field(), 3: parse_add_char('\n')
            if state == _IN_FIELD or state == _AFTER_ESCAPED_CRNL:
                if state == _AFTER_ESCAPED_CRNL and c == _EOL:
                    pass
                elif c == 10 or c == 13 or c == _EOL:
                    # end of line - return [fields]
                    act = 2
                    state = _START_RECORD if c == _EOL else _EAT_CRNL
                elif c == esc:
                    # possible escaped character
                    state = _ESCAPED_CHAR
                elif c == delim:
                    # save field - wait for new field
                    act = 2
                    state = _START_FIELD
                else:
                    # normal character - save in field (AFTER_ESCAPED_CRNL stays)
                    act = 1
            elif state == _IN_QUOTED_FIELD:
                if c == _EOL:
                    pass
                elif c == esc:
                    # Possible escape character
                    state = _ESCAPE_IN_QUOTED_FIELD
                elif c == quote:
                    if d.doublequote:
                        # doublequote; " represented by ""
                        state = _QUOTE_IN_QUOTED_FIELD
                    else:
                        # end of quote part of field
                        state = _IN_FIELD
                else:
                    # normal character - save in field
                    act = 1
            elif state == _START_RECORD and c == _EOL:
                # empty line - return []
                pass
            elif state == _START_RECORD and (c == 10 or c == 13):
                state = _EAT_CRNL
            elif state == _START_RECORD or state == _START_FIELD:
                # expecting field
                state = _START_FIELD
                unquoted = True
                if c == 10 or c == 13 or c == _EOL:
                    # save empty field - return [fields]
                    act = 2
                    state = _START_RECORD if c == _EOL else _EAT_CRNL
                elif c == quote:
                    # start quoted field
                    unquoted = False
                    state = _IN_QUOTED_FIELD
                elif c == esc:
                    # possible escaped character
                    state = _ESCAPED_CHAR
                elif c == 32 and skip:
                    # ignore spaces at start of field
                    pass
                elif c == delim:
                    # save empty field
                    act = 2
                else:
                    # begin new unquoted field
                    act = 1
                    state = _IN_FIELD
            elif state == _ESCAPED_CHAR:
                if c == 10 or c == 13:
                    act = 1
                    state = _AFTER_ESCAPED_CRNL
                else:
                    act = 3 if c == _EOL else 1
                    state = _IN_FIELD
            elif state == _ESCAPE_IN_QUOTED_FIELD:
                act = 3 if c == _EOL else 1
                state = _IN_QUOTED_FIELD
            elif state == _QUOTE_IN_QUOTED_FIELD:
                # doublequote - seen a quote in a quoted field
                if c == quote:
                    # save "" as "
                    act = 1
                    state = _IN_QUOTED_FIELD
                elif c == delim:
                    # save field - wait for new field
                    act = 2
                    state = _START_FIELD
                elif c == 10 or c == 13 or c == _EOL:
                    # end of line - return [fields]
                    act = 2
                    state = _START_RECORD if c == _EOL else _EAT_CRNL
                elif not d.strict:
                    act = 1
                    state = _IN_FIELD
                else:
                    # illegal
                    raise Error("'%s' expected after '%s'" % (d.delimiter, d.quotechar))
            else:  # _EAT_CRNL
                if c == 10 or c == 13:
                    pass
                elif c == _EOL:
                    state = _START_RECORD
                else:
                    raise Error("new-line character seen in unquoted field - do you need to open the file with newline=''?")
            if act == 1:
                if start < 0:
                    start = i
                # and the characters after it that the state adds too, up to the next one it may
                # not: the next delimiter, escapechar, \r or \n of an unquoted field, the next
                # quotechar or escapechar of a quoted one
                if state == _IN_QUOTED_FIELD or state == _IN_FIELD or state == _AFTER_ESCAPED_CRNL:
                    j = line.find(quotes if state == _IN_QUOTED_FIELD else delims, i + w)
                    if j < 0:
                        j = n
                    if esc >= 0:
                        k = line.find(escs, i + w, j)
                        if k >= 0:
                            j = k
                    if state != _IN_QUOTED_FIELD:
                        if nl < i + w:
                            nl = _newline(line, i + w, n)
                        if nl < j:
                            j = nl
                    i = j - w
            else:
                if start >= 0:
                    # the characters added since start
                    flen += i - start
                    if flen > limit:  # (its length in characters is at most that)
                        if not counted:
                            for piece in pieces:
                                fcont += _ncont(piece, 0, len(piece))
                            counted = True
                        fcont += _ncont(line, start, i)
                        if flen - fcont > limit:
                            raise Error("field larger than field limit (%d)" % limit)
                    if act == 2 and len(pieces) == 0:
                        fields.append(line[start:i])
                        flen = 0
                        fcont = 0
                        counted = False
                        act = 0
                    else:
                        pieces.append(line[start:i])
                    start = -1
                if act == 3:
                    flen += 1
                    if flen > limit:
                        if not counted:
                            for piece in pieces:
                                fcont += _ncont(piece, 0, len(piece))
                            counted = True
                        if flen - fcont > limit:
                            raise Error("field larger than field limit (%d)" % limit)
                    pieces.append("\n")
                elif act == 2:
                    self._save(unquoted)
                    flen = 0
                    fcont = 0
                    counted = False
            i += w
        if state == _START_RECORD:
            self._record(line_num)
        self.state = state
        self.flen = flen
        self.unquoted = unquoted

    def _save(self, unquoted: bool) -> None:
        # parse_save_field, of the pieces
        pieces = self.pieces
        if len(pieces) == 0:
            if unquoted and self.notnull:
                self.null = True
            self.fields.append("")
        elif len(pieces) == 1:
            self.fields.append(pieces[0])
            pieces.clear()
        else:
            self.fields.append("".join(pieces))
            pieces.clear()

    def finish(self, line_num: int) -> None:
        # the end of the input: a field cut short ends the last record (Reader_iternext)
        if self.flen != 0 or self.state == _IN_QUOTED_FIELD:
            if self.dialect.strict:
                raise Error("unexpected end of data")
            self._save(self.unquoted)
            self._record(line_num)

    def _record(self, line_num: int) -> None:
        # the record of the fields so far, which Reader_iternext returns
        if self.null:
            raise NotImplementedError("csv.reader with QUOTE_NOTNULL gives None for an empty unquoted field, which the list[str] Pystachy returns cannot hold")
        self.rows.append(self.fields)
        self.lines.append(line_num)
        self.fields = []


def _newline(s: str, i: int, n: int) -> int:
    # the first \r or \n of s from i on, or n
    j = s.find("\n", i)
    if j < 0:
        j = n
    k = s.find("\r", i, j)
    return k if k >= 0 else j


def _ncont(s: str, i: int, j: int) -> int:
    # the continuation bytes of UTF-8 characters in s[i:j] (none in a str of code points)
    k = 0
    if _UTF8:
        for x in range(i, j):
            if ord(s[x]) & 0xC0 == 0x80:
                k += 1
    return k


class Reader:
    # _csv.Reader: what reader() returns. Its first iteration reads the input to its end and parses
    # it into a list of rows, which it steps through; the iterations after it have no rows, as
    # CPython's reader has none once it is exhausted

    def __init__(self, f, dialect: Dialect) -> None:
        self._f = f
        self.dialect = dialect
        self.line_num = 0
        self._started = False

    def _parse(self) -> _Parser:
        # Reader_iternext over all the lines of the input, once
        p = _Parser(self.dialect)
        if not self._started:
            self._started = True
            for line in self._f:
                if isinstance(line, str):
                    self.line_num += 1
                    p.feed(line, self.line_num)
                else:
                    raise Error("iterator should return strings, not %.200s (the file should be opened in text mode)" % _typename(line))
            p.finish(self.line_num)
        return p

    def __iter__(self) -> Iterator[list[str]]:
        rows = self._parse().rows
        return iter(rows)


def reader(csvfile, /, dialect=None, **fmtparams):
    """Return a reader object that will process lines from the given iterable.

    The "iterable" argument can be any object that returns a line
    of input for each iteration, such as a file object or a list.  The
    optional "dialect" argument defines a CSV dialect.  The function
    also accepts optional keyword arguments which override settings
    provided by the dialect.

    The returned object is an iterator.  Each iteration returns a row
    of the CSV file (which can span multiple input lines).
    """
    return Reader(csvfile, _reading(_call_dialect(dialect, **fmtparams)))


def _reading(d: Dialect) -> Dialect:
    # d, which a reader of str fields can read with
    if d.quoting == QUOTE_NONNUMERIC:
        raise NotImplementedError("csv.reader with QUOTE_NONNUMERIC gives floats for the unquoted fields, which the list[str] Pystachy returns cannot hold")
    if d.quoting == QUOTE_STRINGS:
        raise NotImplementedError("csv.reader with QUOTE_STRINGS gives floats for the unquoted fields (None for an empty one), which the list[str] Pystachy returns cannot hold")
    return d


# ---- writing

class Writer:
    # _csv.Writer: what writer() returns. writerow() joins the fields of a row into one line, as
    # join_append() and join_append_data() do, and writes it with the file's write()

    def __init__(self, f, dialect: Dialect) -> None:
        self._f = f
        self.dialect = dialect
        q = dialect.quotechar
        e = dialect.escapechar
        self._quote: str = "" if q is None else q  # ("": none)
        self._esc: str = "" if e is None else e
        self._spaces: bool = dialect.delimiter == " " and dialect.skipinitialspace
        # the characters but these two that a field is quoted for (escaped, with QUOTE_NONE): the
        # delimiter, \n, \r and the lineterminator's
        others = [dialect.delimiter, "\n", "\r"]
        for c in _chars(dialect.lineterminator):
            if c not in others:
                others.append(c)
        self._others: list[str] = others
        # the record being joined: its pieces (the fields, the quotes around them and a delimiter
        # between two), which make its line, and how many fields it has
        self._parts: list[str] = []
        self._nfields = 0

    def _join(self, field: str, null: bool, quoted: bool) -> None:
        # join_append: field (None's is "") added to the record, quoted or not. join_append_data
        # escapes a character of the dialect's in the field (any with QUOTE_NONE; else an
        # escapechar, and a quotechar without doublequote), doubles a quotechar or quotes the field
        # for it: which of them the field holds decides that, so each is replaced throughout, the
        # escapechar first, and the error is the one of the first character it would escape
        d = self.dialect
        quoting = d.quoting
        if self._spaces and len(field) == 0:
            if quoting == QUOTE_NONE or (null and (quoting == QUOTE_STRINGS or quoting == QUOTE_NOTNULL)):
                raise Error("empty field must be quoted if delimiter is a space and skipinitialspace is true")
            quoted = True
        text = field
        quote = self._quote
        esc = self._esc
        hasq = len(quote) > 0 and field.find(quote) >= 0
        hase = len(esc) > 0 and field.find(esc) >= 0
        other = False
        for c in self._others:
            if field.find(c) >= 0:
                other = True
                break
        if hasq or hase or other:
            if quoting == QUOTE_NONE:
                if len(esc) == 0:
                    raise Error("need to escape, but no escapechar set")
                if hase:
                    text = text.replace(esc, esc + esc)
                if hasq:
                    text = text.replace(quote, esc + quote)
                for c in self._others:
                    if field.find(c) >= 0:
                        text = text.replace(c, esc + c)
            else:
                if hasq and not d.doublequote and len(esc) == 0:
                    raise Error("need to escape, but no escapechar set")
                if hase:
                    text = text.replace(esc, esc + esc)
                if hasq:
                    if d.doublequote:
                        text = text.replace(quote, quote + quote)
                        quoted = True
                    else:
                        text = text.replace(quote, esc + quote)
                if other:
                    quoted = True
        parts = self._parts
        if self._nfields > 0:
            parts.append(d.delimiter)
        if quoted:
            parts.append(quote)
            parts.append(text)
            parts.append(quote)
        else:
            parts.append(text)
        self._nfields += 1

    def _append(self, field) -> bool:
        # a field of csv_writerow: quoted as the dialect's quoting says for its type, a str of
        # str(), None as an empty field; whether it is None
        quoting = self.dialect.quoting
        if field is None:
            self._join("", True, quoting == QUOTE_ALL or quoting == QUOTE_NONNUMERIC)
            return True
        if isinstance(field, str):
            self._join(field, False, quoting != QUOTE_MINIMAL and quoting != QUOTE_NONE)
        elif isinstance(field, (int, float)):
            self._join(str(field), False, quoting == QUOTE_ALL or quoting == QUOTE_NOTNULL)
        else:
            self._join(str(field), False, quoting == QUOTE_ALL or quoting == QUOTE_NONNUMERIC or quoting == QUOTE_NOTNULL)
        return False

    def _append_items(self, field, *rest) -> bool:
        # the fields of a tuple, whose items may have different types (iterating a tuple needs one
        # item type): the first, then the others, in a call of their own; whether the last is None
        null = self._append(field)
        if len(rest) > 0:
            return self._append_items(*rest)
        return null

    def _end(self, null):
        # the end of csv_writerow: a record of one empty field is quoted, the line terminated and
        # written; null: whether the last field was None
        parts = self._parts
        quoting = self.dialect.quoting
        if self._nfields == 1 and len(parts) == 1 and len(parts[0]) == 0:
            if quoting == QUOTE_NONE or (null and (quoting == QUOTE_STRINGS or quoting == QUOTE_NOTNULL)):
                raise Error("single empty field record must be quoted")
            parts.pop()
            self._nfields = 0
            self._join("", True, True)
        parts.append(self.dialect.lineterminator)
        return self._f.write("".join(parts))

    def writerow(self, row):
        """Construct and write a CSV record from an iterable of fields.

        Non-string elements will be converted to string.
        """
        self._parts.clear()
        self._nfields = 0
        null = False
        if row is None:
            raise Error("iterable expected, not NoneType")
        if isinstance(row, (int, float)):
            raise Error("iterable expected, not %.200s" % _typename(row))
        elif isinstance(row, tuple):
            if len(row) > 0:
                null = self._append_items(*row)
        elif isinstance(row, str):
            for c in _chars(row):
                null = self._append(c)
        else:
            for field in row:
                null = self._append(field)
        return self._end(null)

    def writerows(self, rows) -> None:
        """Construct and write a series of iterables to a csv file.

        Non-string elements will be converted to string.
        """
        for row in rows:
            self.writerow(row)


def writer(csvfile, /, dialect=None, **fmtparams):
    """Return a writer object that will write user data on the given file object.

    The "fileobj" argument can be any object that supports the file API.
    The optional "dialect" argument defines a CSV dialect.  The function
    also accepts optional keyword arguments which override settings
    provided by the dialect.
    """
    return Writer(csvfile, _call_dialect(dialect, **fmtparams))


