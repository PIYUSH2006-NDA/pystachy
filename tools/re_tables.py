"""Write lib/re/_unicode.py: the Unicode tables that CPython's _sre reads, from CPython itself.

usage: python3 -I tools/re_tables.py > lib/re/_unicode.py   (with the CPython whose re lib/re ports)
_sre's character tests and case mappings are CPython's C functions (Py_UNICODE_ISALNUM and the
others, _PyUnicode_ToLowercase/_ToUppercase, whose result for a character with a special casing is
the first character of its full mapping); this calls them through ctypes, so the tables are theirs
for every code point. re._casefix._EXTRA_CASES is the compiler's table of characters that differ
but share an uppercase.
"""
import ctypes
import sys
import unicodedata
from re import _casefix

api = ctypes.pythonapi


def cfunc(name):
    f = getattr(api, name)
    f.restype = ctypes.c_int if name.startswith("_PyUnicode_Is") else ctypes.c_uint32
    f.argtypes = [ctypes.c_uint32]
    return f


lower = cfunc("_PyUnicode_ToLowercase")
upper = cfunc("_PyUnicode_ToUppercase")
isalpha = cfunc("_PyUnicode_IsAlpha")
isdecimal = cfunc("_PyUnicode_IsDecimalDigit")
isdigit = cfunc("_PyUnicode_IsDigit")
isnumeric = cfunc("_PyUnicode_IsNumeric")
iswhitespace = cfunc("_PyUnicode_IsWhitespace")
islinebreak = cfunc("_PyUnicode_IsLinebreak")
ASCII_SPACE = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x1C, 0x1D, 0x1E, 0x1F, 0x20}  # (_Py_ascii_whitespace)
N = sys.maxunicode + 1


def b36(n):
    s = ""
    while True:
        n, d = divmod(n, 36)
        s = "0123456789abcdefghijklmnopqrstuvwxyz"[d] + s
        if n == 0:
            return s


def ranges(test):
    # the code points where test holds, as start and end-plus-one, each written as the distance from
    # the number before it (the first from 0)
    out, prev, start = [], 0, -1
    for c in range(N + 1):
        t = c < N and test(c)
        if t and start < 0:
            start = c
        elif not t and start >= 0:
            out += [start - prev, c - start]
            prev, start = c, -1
    return " ".join(b36(x) for x in out)


def mapping(f):
    # the code points that f maps elsewhere: each as the distance from the one before, and the
    # mapped value's difference from it (after ":" up, after "-" down)
    out, prev = [], 0
    for c in range(N):
        m = f(c)
        if m != c:
            out.append(b36(c - prev) + ("-" + b36(c - m) if m < c else ":" + b36(m - c)))
            prev = c
    return " ".join(out)


def wrap(name, s, comment):
    lines = [f"# {comment}", f"{name} = ("]
    while s:
        cut = s[:96]
        if len(s) > 96:
            cut = cut[: cut.rfind(" ") + 1]
        lines.append(f"    {cut!r}")
        s = s[len(cut):]
    lines.append(")")
    return "\n".join(lines)


extra = " ".join(b36(k) + ":" + ",".join(b36(v) for v in vs) for k, vs in sorted(_casefix._EXTRA_CASES.items()))
print(f'''# Generated by tools/re_tables.py from CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}): do not edit.
# The Unicode tables of CPython's _sre, which re's engine (_sre.py) and compiler read, as base-36
# numbers: ranges are the distance from the previous boundary to each start, then each length;
# mappings are the distance from the previous mapped code point, then ":" and how far up it maps
# (or "-" and how far down). _sre.py decodes them the first time a character outside ASCII needs
# one (see _table).
''')
print(wrap("ALNUM", ranges(lambda c: isalpha(c) or isdecimal(c) or isdigit(c) or isnumeric(c)), "Py_UNICODE_ISALNUM: \\w is these and '_'"))
print()
print(wrap("DECIMAL", ranges(isdecimal), "Py_UNICODE_ISDECIMAL: \\d"))
print()
print(wrap("SPACE", ranges(lambda c: c in ASCII_SPACE if c < 128 else iswhitespace(c)), "Py_UNICODE_ISSPACE: \\s"))
print()
print(wrap("LINEBREAK", ranges(islinebreak), "Py_UNICODE_ISLINEBREAK"))
print()
print(wrap("IDSTART", ranges(lambda c: chr(c).isidentifier()), "str.isidentifier() of the character: XID_Start, and '_'"))
print()
print(wrap("IDCONTINUE", ranges(lambda c: ("a" + chr(c)).isidentifier()), "XID_Continue: the characters an identifier goes on with"))
print()
print(wrap("ALPHA_IDSTART_DELTA", ranges(lambda c: bool(isalpha(c)) != chr(c).isidentifier()),
           "str.isalpha() differs from single-character str.isidentifier(), over U+0000..U+10FFFF"))
print()
print(wrap("LOWER", mapping(lower), "Py_UNICODE_TOLOWER"))
print()
print(wrap("UPPER", mapping(upper), "Py_UNICODE_TOUPPER"))
print()
print(wrap("EXTRA_CASES", extra, "re._casefix._EXTRA_CASES: a lowercase character, ':', and the others that share its uppercase"))
