"""Write lib/_pystachy_unicodedata_db.py and _pystachy_unicodedata_names.py: the tables of the
unicodedata stand-in (lib/_pystachy_unicodedata.py), from CPython itself.

usage: python3 -I tools/unicodedata_tables.py UCD_DIR [LIBDIR]
       (with the CPython whose unicodedata lib/ ports; UCD_DIR holds that Unicode version's
       NameAliases.txt, NamedSequences.txt and NormalizationCorrections.txt; LIBDIR is lib/)
Each table is what CPython's unicodedata functions give, asked for every code point:
- the properties: category(), bidirectional(), east_asian_width(), mirrored() and combining();
- decimal(), digit() and numeric();
- decomposition();
- the canonical compositions that normalize('NFC') makes of two characters;
- the names (name()), and the names that only lookup() takes (aliases, named sequences and the
  Tangut ideographs' derived names);
- the same for ucd_3_2_0, where it differs.
The Unicode files give what CPython's tables keep but no function lists: the aliases and named
sequences, and the decompositions that Unicode corrected after 3.2.0, which ucd_3_2_0.normalize()
uses. Each one is checked against CPython's lookup() and ucd_3_2_0.normalize().
"""
import os
import sys
import unicodedata

N = sys.maxunicode + 1
OLD = unicodedata.ucd_3_2_0
SBASE, SCOUNT = 0xAC00, 11172
B36 = "0123456789abcdefghijklmnopqrstuvwxyz"


def b36(n):
    s = ""
    while True:
        n, d = divmod(n, 36)
        s = B36[d] + s
        if n == 0:
            return s


def lines(items, width=96):
    # a Python string literal of the items joined by spaces, as lines of at most width characters
    out, cur = [], ""
    for x in items:
        if cur and len(cur) + 1 + len(x) > width:
            out.append(cur + " ")
            cur = x
        else:
            cur = cur + " " + x if cur else x
    out.append(cur)
    return "(\n" + "".join(f"    {s!r}\n" for s in out) + ")"


def runs(value):
    # the code points' values as runs: the distance from the previous run's start, then the value
    out, prev, last = [], 0, None
    for c in range(N):
        v = value(c)
        if c == 0 or v != last:
            out += [b36(c - prev), b36(v)]
            prev, last = c, v
    return out


def ranges(test):
    # the code points where test holds, as start and end-plus-one, each the distance from the one
    # before it (the first from 0)
    out, prev, start = [], 0, -1
    for c in range(N + 1):
        t = c < N and test(c)
        if t and start < 0:
            start = c
        elif not t and start >= 0:
            out += [b36(start - prev), b36(c - start)]
            prev, start = c, -1
    return out


def ucd_file(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip()
            if line:
                yield [x.strip() for x in line.split(";")]


def db(ucd_dir):
    out = [f"# Generated by tools/unicodedata_tables.py from CPython {sys.version.split()[0]} (Unicode "
           f"{unicodedata.unidata_version}): do not edit.",
           "# unicodedata's tables, as base-36 numbers (_pystachy_unicodedata.py decodes each the first time",
           "# it needs one). PROPS are the records of the properties each code point has: the indexes in",
           "# CATEGORIES, BIDIRECTIONAL and EAST_ASIAN_WIDTHS, then mirrored() and combining(); RUNS and",
           "# RUNS_3_2_0 give each code point's record as runs (the distance from the start of the run before,",
           "# then the record).", ""]
    chars = [chr(c) for c in range(N)]
    cats = sorted({unicodedata.category(ch) for ch in chars} | {OLD.category(ch) for ch in chars})
    bidis = sorted({unicodedata.bidirectional(ch) for ch in chars} | {OLD.bidirectional(ch) for ch in chars})
    eaws = sorted({unicodedata.east_asian_width(ch) for ch in chars} | {OLD.east_asian_width(ch) for ch in chars})
    recs = {}

    def record(u, c):
        ch = chars[c]
        k = (cats.index(u.category(ch)), bidis.index(u.bidirectional(ch)), eaws.index(u.east_asian_width(ch)),
             u.mirrored(ch), u.combining(ch))
        return recs.setdefault(k, len(recs))

    new_runs = runs(lambda c: record(unicodedata, c))
    old_runs = runs(lambda c: record(OLD, c))
    out.append(f"CATEGORIES = {' '.join(cats)!r}")
    out.append(f"BIDIRECTIONAL = {' '.join(b if b else '-' for b in bidis)!r}  # (- is the empty string)")
    out.append(f"EAST_ASIAN_WIDTHS = {' '.join(eaws)!r}")
    out.append(f"PROPS = {lines([b36(x) for k in sorted(recs, key=recs.get) for x in k])}")
    out.append(f"RUNS = {lines(new_runs)}")
    out.append(f"RUNS_3_2_0 = {lines(old_runs)}")
    # (the code points ucd_3_2_0 has no character for, where the current version has one: CPython's
    # change records with a category of 0)
    out.append("# the code points unassigned in Unicode 3.2.0 but assigned now, as ranges (start and length, the")
    out.append("# start the distance from the end of the range before)")
    out.append(f"UNASSIGNED_3_2_0 = {lines(ranges(lambda c: OLD.category(chars[c]) == 'Cn' and unicodedata.category(chars[c]) != 'Cn'))}")
    # decimal(), digit() and numeric(): the distance from the code point before, then decimal + 1,
    # digit + 1 and the index of numeric's value + 1 (0 for none)
    values = sorted({unicodedata.numeric(ch) for ch in chars if unicodedata.numeric(ch, None) is not None}
                    | {OLD.numeric(ch) for ch in chars if OLD.numeric(ch, None) is not None})
    num, prev = [], 0
    for c in range(N):
        ch = chars[c]
        d, g, v = unicodedata.decimal(ch, None), unicodedata.digit(ch, None), unicodedata.numeric(ch, None)
        if d is not None or g is not None or v is not None:
            num += [b36(c - prev), b36(0 if d is None else d + 1), b36(0 if g is None else g + 1),
                    b36(0 if v is None else values.index(v) + 1)]
            prev = c
    out.append("# decimal(), digit() and numeric(): the distance from the code point before, then decimal + 1,")
    out.append("# digit + 1 and 1 + the index of numeric's value in NUMERIC_VALUES (0: none)")
    out.append(f"NUMERIC_VALUES = {lines([repr(v) for v in values])}")
    out.append(f"NUMERIC = {lines(num)}")
    num, prev = [], 0
    for c in range(N):
        ch = chars[c]
        if OLD.category(ch) == "Cn":
            continue  # (unassigned: none, see UNASSIGNED_3_2_0)
        d, v = OLD.decimal(ch, None), OLD.numeric(ch, None)
        if d != unicodedata.decimal(ch, None) or v != unicodedata.numeric(ch, None):
            num += [b36(c - prev), b36(0 if d is None else d + 1), b36(0 if v is None else values.index(v) + 1)]
            prev = c
    out.append("# ucd_3_2_0's decimal() and numeric() where they differ, for characters it has: the distance, then")
    out.append("# decimal + 1 and the index + 1 of numeric's value (digit() is the current version's)")
    out.append(f"NUMERIC_3_2_0 = {lines(num)}")
    # decomposition(), but of the Hangul syllables (_pystachy_unicodedata.py makes theirs)
    tags = [""]
    dec, prev = [], 0
    for c in range(N):
        if SBASE <= c < SBASE + SCOUNT:
            continue
        s = unicodedata.decomposition(chars[c])
        if not s:
            continue
        parts = s.split()
        tag = parts.pop(0) if parts[0].startswith("<") else ""
        if tag not in tags:
            tags.append(tag)
        dec += [b36(c - prev), b36(tags.index(tag) * 32 + len(parts))] + [b36(int(p, 16)) for p in parts]
        prev = c
    out.append("# decomposition(): the distance from the code point before, then 32 * the index of its tag in")
    out.append("# DECOMPOSITION_TAGS + the number of code points, then the code points")
    out.append(f"DECOMPOSITION_TAGS = {' '.join(t if t else '-' for t in tags)!r}  # (- is no tag)")
    out.append(f"DECOMPOSITIONS = {lines(dec)}")
    # the compositions: of each canonical decomposition of two characters that normalize('NFC')
    # composes again (CPython's comp_data)
    comp = []
    for c in range(N):
        if SBASE <= c < SBASE + SCOUNT:
            continue
        parts = unicodedata.decomposition(chars[c]).split()
        if len(parts) == 2 and not parts[0].startswith("<"):
            a, b = int(parts[0], 16), int(parts[1], 16)
            if unicodedata.normalize("NFC", chr(a) + chr(b)) == chars[c]:
                comp += [b36(a), b36(b), b36(c)]
    out.append("# the canonical compositions: the first character, the last, the composite")
    out.append(f"COMPOSITIONS = {lines(comp)}")
    # ucd_3_2_0.normalize()'s corrected decompositions: Unicode's corrections after 3.2.0, as
    # CPython's normalization_3_2_0() keeps them (one code point each)
    fix = []
    for code, old, new, version in ucd_file(os.path.join(ucd_dir, "NormalizationCorrections.txt")):
        if tuple(int(x) for x in version.split(".")) > (3, 2, 0):
            c, v = int(code, 16), int(old, 16)
            assert OLD.normalize("NFD", chr(c)) == unicodedata.normalize("NFD", chr(v)), code
            fix += [b36(c), b36(v)]
    out.append("# ucd_3_2_0.normalize()'s decompositions that Unicode corrected later: the code point, its 3.2.0 one")
    out.append(f"NORMALIZATION_3_2_0 = {' '.join(fix)!r}")
    return "\n".join(out) + "\n"


def names(ucd_dir):
    out = [f"# Generated by tools/unicodedata_tables.py from CPython {sys.version.split()[0]} (Unicode "
           f"{unicodedata.unidata_version}): do not edit.",
           "# unicodedata's names (_pystachy_unicodedata.py decodes them the first time name() or lookup() needs",
           "# them). NAMES gives each named code point, but for the derived names (HANGUL SYLLABLE ..., CJK",
           "# UNIFIED IDEOGRAPH-XXXX) and those in SUFFIXED, as the distance from the code point before, the",
           "# number of its words, then their indexes in WORDS.", ""]
    chars = [chr(c) for c in range(N)]
    cjk = [c for c in range(N) if unicodedata.name(chars[c], "") == f"CJK UNIFIED IDEOGRAPH-{c:04X}"]
    tangut = []
    for c in range(0x10000, N):
        try:
            if unicodedata.lookup(f"TANGUT IDEOGRAPH-{c:04X}") == chars[c]:
                tangut.append(c)
        except KeyError:
            pass
    named = {}
    suffixed = {}  # (prefix: the code points named prefix-XXXX, their own code point in hex)
    for c in range(N):
        n = unicodedata.name(chars[c], None)
        if n is None or SBASE <= c < SBASE + SCOUNT or n == f"CJK UNIFIED IDEOGRAPH-{c:04X}":
            continue
        if n.endswith(f"-{c:04X}"):
            suffixed.setdefault(n[: -len(f"-{c:04X}")], []).append(c)
            continue
        named[c] = n
    count = {}
    for n in named.values():
        for w in n.split(" "):
            count[w] = count.get(w, 0) + 1
    words = sorted(count, key=lambda w: (-count[w], w))  # (the commonest first: the shortest indexes)
    index = {w: i for i, w in enumerate(words)}
    enc, prev = [], 0
    for c in sorted(named):
        ws = named[c].split(" ")
        enc += [b36(c - prev), b36(len(ws))] + [b36(index[w]) for w in ws]
        prev = c
    assert all(w for w in words)
    out.append(f"WORDS = {lines(words)}")
    out.append("# the indexes of WORDS in the order of the words (lookup() searches them)")
    out.append(f"WORD_ORDER = {lines([b36(i) for i in sorted(range(len(words)), key=lambda i: words[i])])}")
    out.append(f"NAMES = {lines(enc)}")

    def as_ranges(cs):
        r, prev, i = [], 0, 0
        while i < len(cs):
            j = i
            while j + 1 < len(cs) and cs[j + 1] == cs[j] + 1:
                j += 1
            r += [b36(cs[i] - prev), b36(cs[j] - cs[i] + 1)]
            prev = cs[j] + 1
            i = j + 1
        return r

    out.append("# the code points of the derived names CJK UNIFIED IDEOGRAPH-XXXX (name() and lookup()) and TANGUT")
    out.append("# IDEOGRAPH-XXXX (lookup() only), as ranges (start and length, the start the distance from the end")
    out.append("# of the range before)")
    out.append(f"CJK = {lines(as_ranges(cjk))}")
    out.append("# the names that end in their code point in hex (at least four digits), as each prefix, ':' and its")
    out.append("# code points as ranges")
    out.append("SUFFIXED = (\n" + "".join(f"    {p + ':' + ' '.join(as_ranges(cs))!r},\n" for p, cs in sorted(suffixed.items())) + ")")
    out.append(f"TANGUT = {lines(as_ranges(tangut))}")
    aliases = []
    for code, name, kind in ucd_file(os.path.join(ucd_dir, "NameAliases.txt")):
        assert unicodedata.lookup(name) == chr(int(code, 16)), name
        aliases.append(f"{int(code, 16):x}:{name}")
    out.append("# the aliases lookup() takes (Unicode's NameAliases.txt), each the code point in hex, ':' and the name")
    out.append("ALIASES = (\n" + "".join(f"    {a!r},\n" for a in aliases) + ")")
    seqs = []
    for name, cps in ucd_file(os.path.join(ucd_dir, "NamedSequences.txt")):
        assert unicodedata.lookup(name) == "".join(chr(int(x, 16)) for x in cps.split()), name
        seqs.append(f"{' '.join(f'{int(x, 16):x}' for x in cps.split())}:{name}")
    out.append("# the named sequences lookup() takes (Unicode's NamedSequences.txt): the code points in hex, ':' and the name")
    out.append("NAMED_SEQUENCES = (\n" + "".join(f"    {a!r},\n" for a in seqs) + ")")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: python3 -I tools/unicodedata_tables.py UCD_DIR [LIBDIR]")
    lib = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib")
    for name, text in (("_pystachy_unicodedata_db.py", db(sys.argv[1])), ("_pystachy_unicodedata_names.py", names(sys.argv[1]))):
        with open(os.path.join(lib, name), "w", encoding="utf-8") as f:
            f.write(text)
        print(f"{name}: {len(text)} bytes")


if __name__ == "__main__":
    main()
