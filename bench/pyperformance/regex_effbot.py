
"""Benchmarks for Python's regex engine.

These are some of the original benchmarks used to tune Python's regex engine
in 2000 written by Fredrik Lundh. Retreived from
http://mail.python.org/pipermail/python-dev/2000-August/007797.html and
integrated into Unladen Swallow's pyperf.py in 2009 by David Laing.

These benchmarks are of interest since they helped to guide the original
optimization of the sre engine, and we shouldn't necessarily ignore them just
because they're "old".
"""

# Python imports
import re

# Local imports
# Pystachy port: pyperf is not imported; the main below replaces pyperf.Runner.
# The benchmark times what pyperf would time with time.perf_counter(), which is
# pyperf.perf_counter(), and appends the seconds to TIMED; the main prints their sum.
import time

TIMED = []

USE_BYTES = False


def re_compile(s):
    # Pystachy port: the bytes branch is left out (there are no bytes; USE_BYTES is
    # never set)
    # if USE_BYTES:
    #     return re.compile(s.encode('latin1'))
    # else:
    return re.compile(s)

# These are the regular expressions to be tested. These sync up,
# index-for-index with the list of strings generated by gen_string_table()
# below.


def gen_regex_table():
    return [
        re_compile('Python|Perl'),
        re_compile('Python|Perl'),
        re_compile('(Python|Perl)'),
        re_compile('(?:Python|Perl)'),
        re_compile('Python'),
        re_compile('Python'),
        re_compile('.*Python'),
        re_compile('.*Python.*'),
        re_compile('.*(Python)'),
        re_compile('.*(?:Python)'),
        re_compile('Python|Perl|Tcl'),
        re_compile('Python|Perl|Tcl'),
        re_compile('(Python|Perl|Tcl)'),
        re_compile('(?:Python|Perl|Tcl)'),
        re_compile('(Python)\\1'),
        re_compile('(Python)\\1'),
        re_compile('([0a-z][a-z0-9]*,)+'),
        re_compile('(?:[0a-z][a-z0-9]*,)+'),
        re_compile('([a-z][a-z0-9]*,)+'),
        re_compile('(?:[a-z][a-z0-9]*,)+'),
        re_compile('.*P.*y.*t.*h.*o.*n.*')]


def gen_string_table(n):
    """Generates the list of strings that will be used in the benchmarks.

    All strings have repeated prefixes and suffices, and n specifies the
    number of repetitions.
    """
    strings: list[str] = []  # Pystachy port: annotated

    def append(s):
        # Pystachy port: the bytes branch is left out (see re_compile())
        # if USE_BYTES:
        #     strings.append(s.encode('latin1'))
        # else:
        strings.append(s)
    append('-' * n + 'Perl' + '-' * n)
    append('P' * n + 'Perl' + 'P' * n)
    append('-' * n + 'Perl' + '-' * n)
    append('-' * n + 'Perl' + '-' * n)
    append('-' * n + 'Python' + '-' * n)
    append('P' * n + 'Python' + 'P' * n)
    append('-' * n + 'Python' + '-' * n)
    append('-' * n + 'Python' + '-' * n)
    append('-' * n + 'Python' + '-' * n)
    append('-' * n + 'Python' + '-' * n)
    append('-' * n + 'Perl' + '-' * n)
    append('P' * n + 'Perl' + 'P' * n)
    append('-' * n + 'Perl' + '-' * n)
    append('-' * n + 'Perl' + '-' * n)
    append('-' * n + 'PythonPython' + '-' * n)
    append('P' * n + 'PythonPython' + 'P' * n)
    append('-' * n + 'a5,b7,c9,' + '-' * n)
    append('-' * n + 'a5,b7,c9,' + '-' * n)
    append('-' * n + 'a5,b7,c9,' + '-' * n)
    append('-' * n + 'a5,b7,c9,' + '-' * n)
    append('-' * n + 'Python' + '-' * n)
    return strings


def init_benchmarks(n_values=None):
    """Initialize the strings we'll run the regexes against.

    The strings used in the benchmark are prefixed and suffixed by
    strings that are repeated n times.

    The sequence n_values contains the values for n.
    If n_values is None the values of n from the original benchmark
    are used.

    The generated list of strings is cached in the string_tables
    variable, which is indexed by n.

    Returns:
    A list of string prefix/suffix lengths.
    """

    if n_values is None:
        n_values = (0, 5, 50, 250, 1000, 5000, 10000)

    # Pystachy port: a loop for a dict comprehension (not supported)
    string_tables = {}
    for n in n_values:
        string_tables[n] = gen_string_table(n)
    regexs = gen_regex_table()

    data = []
    for n in n_values:
        for id in range(len(regexs)):
            regex = regexs[id]
            string = string_tables[n][id]
            data.append((regex, string))
    return data


def bench_regex_effbot(loops):
    # Pystachy port: a global for the function attribute bench_regex_effbot.data
    # (functions have no attributes)
    global bench_regex_effbot_data
    if bench_regex_effbot_data is None:
        bench_regex_effbot_data = init_benchmarks()
    data = bench_regex_effbot_data

    range_it = list(range(loops))  # Pystachy port: a list; a range is not a value
    search = re.search
    t0 = time.perf_counter()  # Pystachy port: time.perf_counter() is pyperf.perf_counter()

    for _ in range_it:
        # Runs all of the benchmarks for a given value of n.
        for regex, string in data:
            # search 10 times
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)
            search(regex, string)

    TIMED.append(time.perf_counter() - t0)  # Pystachy port: the seconds, which upstream returns
    # Pystachy port: the match positions, for the checksum
    total = 0
    for regex, string in data:
        m = search(regex, string)
        if m is not None:
            total += m.start() + m.end()
    return total


# cached data, generated at the first call
bench_regex_effbot_data: list[tuple[re.Pattern, str]] | None = None  # Pystachy port: see above


def add_cmdline_args(cmd, args):
    if args.force_bytes:
        cmd.append("--force_bytes")


if __name__ == '__main__':
    # Pystachy port: a deterministic main replaces pyperf.Runner: argv[1] is the
    # number of loops; a checksum of the matches is printed, and the time goes to
    # stderr.
    import sys
    loops = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    result = bench_regex_effbot(loops)
    print("seconds", sum(TIMED), file=sys.stderr)
    print("regex_effbot", loops, result)
